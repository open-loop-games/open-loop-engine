#!/usr/bin/env python3
"""Formula oracle generator — high-precision reference values for the conformance suite.

Emits ``tests/core/fixtures/formula-oracle.json``: for each op, the exact forward
value at each sample point, computed at 40 significant digits with mpmath.

Why a fixture rather than calling out at test time: the suite stays hermetic and
fast (no Python in the vitest run), and the reference values are reviewable in a
diff. Regenerate when a sample point or op is added:

    pip install mpmath        # dev-only; not a package dependency
    python3 scripts/formula-oracle.py

What the oracle buys that a round-trip cannot: a round-trip passes whenever
forward and inverse are *consistently* wrong, and it cannot distinguish an
implementation defect from the conditioning of the function. Comparing the
forward value against an independent high-precision reference separates those.

Samples deliberately stop below 1e308. Above it the reference cannot hold the
value at all — break_eternity's representation is itself logarithmic there — so
those regimes are covered by log-space and algebraic laws in the suite instead,
not by this fixture.
"""

import json
import pathlib

try:
    import mpmath as mp
except ModuleNotFoundError:  # pragma: no cover - operator-facing message
    raise SystemExit("mpmath is required: pip install mpmath (dev-only oracle)")

DPS = 40
mp.mp.dps = DPS

# Sample points per admissible domain. Kept independent of the suite's own
# round-trip domains: those laws need no oracle and own their sampling, so
# neither table is derived from the other.
DOMAINS = {
    "positive": ["0.25", "1", "2.5", "10", "137.5", "1e3", "1e7", "1e15", "1e100", "1e300"],
    "real": ["-137.5", "-2.5", "-0.25", "0", "0.25", "2.5", "10", "137.5", "1e3"],
    "unit": ["-0.9", "-0.5", "-0.25", "0", "0.25", "0.5", "0.9"],
    "unit_positive": ["0", "0.25", "0.5", "0.75", "0.9"],
    "at_least_one": ["1", "1.5", "2.5", "10", "137.5", "1e3", "1e7"],
    "principal": ["-1.5", "-1", "-0.5", "-0.25", "0", "0.25", "0.5", "1", "1.5"],
    "principal_cos": ["0", "0.25", "1", "1.5", "2.5", "3.1"],
    "modest": ["-10", "-2.5", "-0.25", "0", "0.25", "2.5", "10"],
    "modest_positive": ["0", "0.25", "2.5", "10"],
}

# op name -> (mpmath forward function, domain key). Names match the engine's
# op table so the suite can key straight off them.
UNARY_OPS = {
    "neg": (lambda x: -x, "real"),
    "recip": (lambda x: 1 / x, "positive"),
    "log10": (mp.log10, "positive"),
    "log2": (lambda x: mp.log(x, 2), "positive"),
    "ln": (mp.log, "positive"),
    "pow10": (lambda x: mp.mpf(10) ** x, "real"),
    "exp": (mp.exp, "real"),
    "sin": (mp.sin, "principal"),
    "cos": (mp.cos, "principal_cos"),
    "tan": (mp.tan, "principal"),
    "asin": (mp.asin, "unit"),
    "acos": (mp.acos, "unit_positive"),
    "atan": (mp.atan, "real"),
    "sinh": (mp.sinh, "modest"),
    "cosh": (mp.cosh, "modest_positive"),
    "tanh": (mp.tanh, "modest"),
    "asinh": (mp.asinh, "modest"),
    "acosh": (mp.acosh, "at_least_one"),
    "atanh": (mp.atanh, "unit"),
}

# Definite integrals of the integrable ops, as (op, lower, upper) triples. The
# engine exposes an *antiderivative*, so the law it must satisfy is
# `F(b) - F(a) == integral(a, b)` — the constant cancels.
INTEGRALS = [
    ("recip", "1", "10"),
    ("ln", "1", "10"),
    ("log10", "1", "10"),
    ("log2", "1", "10"),
    ("exp", "0", "5"),
    ("pow10", "0", "3"),
    ("sin", "0", "1.5"),
    ("cos", "0", "1.5"),
    ("sinh", "0", "2.5"),
    ("cosh", "0", "2.5"),
]


def fmt(value) -> str:
    """Render at full working precision, so the JSON carries every digit."""
    return mp.nstr(value, DPS, strip_zeros=False)


def main() -> None:
    unary = {}
    for name, (fn, domain) in UNARY_OPS.items():
        samples = []
        for raw in DOMAINS[domain]:
            x = mp.mpf(raw)
            try:
                y = fn(x)
            except (ValueError, ZeroDivisionError):
                continue
            if not mp.isfinite(y):
                continue
            samples.append({"x": raw, "y": fmt(y)})
        unary[name] = {"domain": domain, "samples": samples}

    integrals = []
    for name, lo, hi in INTEGRALS:
        fn = UNARY_OPS[name][0]
        value = mp.quad(fn, [mp.mpf(lo), mp.mpf(hi)])
        integrals.append({"op": name, "from": lo, "to": hi, "value": fmt(value)})

    payload = {
        "$comment": "Generated by scripts/formula-oracle.py — do not hand-edit.",
        "generator": f"mpmath {mp.__version__}",
        "significantDigits": DPS,
        "domains": DOMAINS,
        "unary": unary,
        "integrals": integrals,
    }

    out = pathlib.Path(__file__).resolve().parent.parent / "tests/core/fixtures/formula-oracle.json"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(payload, indent=2) + "\n")
    print(f"wrote {out.relative_to(out.parent.parent.parent)}")
    print(f"  {len(unary)} unary ops, {sum(len(v['samples']) for v in unary.values())} samples")
    print(f"  {len(integrals)} definite integrals")


if __name__ == "__main__":
    main()
